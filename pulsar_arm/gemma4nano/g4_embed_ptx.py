#!/usr/bin/env python3
"""Embed g4_kernels.ptx as a C string (g4_ptx_k.h) so the engine binary is self-contained.
Usage: python3 -I g4_embed_ptx.py g4_kernels.ptx g4_ptx_k.h"""
import sys

src, out = sys.argv[1], sys.argv[2]
lines = open(src, encoding="ascii").read().splitlines()
with open(out, "w", encoding="ascii") as f:
    f.write("/* generated by g4_embed_ptx.py from g4_kernels.ptx (nvcc -arch=compute_53 -ptx -fmad=false -O3) */\n")
    f.write("static const char G4_PTX_K[] =\n")
    for ln in lines:
        f.write('\t"' + ln.replace("\\", "\\\\").replace('"', '\\"') + '\\n"\n')
    f.write(";\n")
